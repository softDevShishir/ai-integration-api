package com.example.claudeintegration.service;

import com.example.claudeintegration.dto.Product;
import org.springframework.stereotype.Service;

import java.util.List;
import java.util.stream.Collectors;

/**
 * Retrieval-augmented generation over the product catalogue:
 * retrieve matching products, augment the system prompt with them, then
 * generate the answer with Claude, Gemini or OpenAI.
 */
@Service
public class RagService {

    static final String INSTRUCTIONS = "You are the assistant for an online store. Answer ONLY using the "
            + "product information below. If the answer is not there, say you don't know and suggest "
            + "contacting support.";

    static final String NO_PRODUCTS = "No matching products were found.";

    private final RetrievalService retrievalService;
    private final GeminiService geminiService;
    private final ClaudeService claudeService;
    private final OpenAiService openAiService;

    public RagService(RetrievalService retrievalService, GeminiService geminiService,
                      ClaudeService claudeService, OpenAiService openAiService) {
        this.retrievalService = retrievalService;
        this.geminiService = geminiService;
        this.claudeService = claudeService;
        this.openAiService = openAiService;
    }

    /**
     * Answers a customer question using only the products retrieved for it,
     * generated by {@code provider} as resolved by {@link ProviderResolver}
     * ({@value ProviderResolver#CLAUDE}, {@value ProviderResolver#GEMINI} or
     * {@value ProviderResolver#OPENAI}).
     *
     * @throws com.example.claudeintegration.exception.GeminiApiException if the call to Gemini fails
     * @throws com.example.claudeintegration.exception.ClaudeApiException if the call to Claude fails
     * @throws com.example.claudeintegration.exception.OpenAiApiException if the call to OpenAI fails
     * @throws IllegalArgumentException if {@code provider} is not one of the above
     */
    public AiResponse answer(String question, String provider) {
        String systemPrompt = buildSystemPrompt(retrievalService.search(question));
        return switch (provider) {
            case ProviderResolver.CLAUDE -> claudeService.ask(systemPrompt, question);
            case ProviderResolver.GEMINI -> geminiService.ask(systemPrompt, question);
            case ProviderResolver.OPENAI -> openAiService.ask(systemPrompt, question);
            default -> throw new IllegalArgumentException("Unsupported provider: " + provider);
        };
    }

    /**
     * Builds the system prompt: the fixed instructions followed by one block
     * per product (or a "nothing found" note, so Claude says it doesn't know).
     */
    String buildSystemPrompt(List<Product> products) {
        String context = products.isEmpty()
                ? NO_PRODUCTS
                : products.stream().map(RagService::format).collect(Collectors.joining("\n\n"));

        return INSTRUCTIONS + "\n\nProduct information:\n\n" + context;
    }

    private static String format(Product product) {
        return "- " + product.name() + "\n"
                + "  Category: " + product.category() + "\n"
                + "  Price: " + product.price().toPlainString() + " BDT\n"
                + "  Availability: " + (product.inStock() ? "In stock" : "Out of stock") + "\n"
                + "  Description: " + product.description();
    }
}
